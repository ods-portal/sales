function toSlug(label: string) {
  return label.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

export function indianStateDropdowns() {
  return INDIAN_STATES.map((label, index) => ({
    group: 'state' as const,
    label,
    value: toSlug(label),
    order: index + 1,
  }));
}
